package ch03;

public class Ex03 {

	public static void main(String[] args) {
		int a =10;
		int b =2;
		//비교 연산자의 리턴값은 블린
		System.out.println(a==b);//JSP에서는 eq로 사용 
		System.out.println(a!=b);//ne사용 프로그램에서 !는 부정의 의미
		System.out.println(a>b);
		System.out.println(a>=b);
		System.out.println(a<b);
		System.out.println(a<=b);
	}

}
